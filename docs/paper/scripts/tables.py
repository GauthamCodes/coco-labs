"""
R3.7: the paper's tables, generated from committed data (never typed).

    python docs/paper/scripts/tables.py [--check]

Writes docs/paper/generated/suites_table.tex (COCO-Bench v1, from the frozen suite files).
"""
import argparse
import json
from pathlib import Path
import sys

REPO = Path(__file__).resolve().parents[3]
GEN = REPO / 'docs' / 'paper' / 'generated'
FAM = {'planning': 'P', 'control': 'C', 'localisation': 'L', 'fulltask': 'T'}


def tt(s):
    return '\\texttt{' + s.replace('_', '\\_') + '}'


def suites_table():
    rows = []
    for p in sorted((REPO / 'coco_lab' / 'coco_lab' / 'benchmarks').glob('*.v1.json')):
        s = json.loads(p.read_text())
        c = s['tiers']['counts']
        world = s.get('world') or '+'.join(w.replace('coco_', '').replace('_v1', '')
                                           for w in s['worlds'])
        world = world.replace('coco_', '').replace('_v1', '')
        rows.append(f"{tt(s['id'])} & {''.join(FAM[f] for f in s['families'])} & "
                    f"{len(s['scenarios'])} & {c['easy']}/{c['medium']}/{c['hard']} & "
                    f"{s['held_out']['n']} & {tt(world)} \\\\")
    return '\n'.join([
        '% GENERATED by docs/paper/scripts/tables.py from coco_lab/coco_lab/benchmarks/*.v1.json',
        '\\begin{table}[t]', '\\centering', '\\small',
        '\\caption{COCO-Bench v1. Families: P planning, C control, L localisation, T full task. '
        'Tiers easy/medium/hard; held-out scenarios drawn per evaluation.}',
        '\\label{tab:suites}', '\\setlength{\\tabcolsep}{3pt}',
        '\\begin{tabular}{lcrcrl}', '\\toprule',
        'suite & fam. & $n$ & tiers & held-out & world \\\\', '\\midrule',
        *rows, '\\bottomrule', '\\end{tabular}', '\\end{table}', ''])


BENCH = REPO / 'docs' / 'v2' / 'r3' / 'bench'
#: the headline metric per family (median over the public scenarios), and its column header
HEADLINE = {'planning': ('path_length_m', 'path (m)'), 'control': ('time_s', 'time (s)'),
            'localisation': ('mean_err_xy_m', 'mean err.\\ (m)')}


def _suite_ids(family):
    out = []
    for p in sorted((REPO / 'coco_lab' / 'coco_lab' / 'benchmarks').glob('*.v1.json')):
        s = json.loads(p.read_text())
        if family in s['families']:
            out.append(s['id'])
    return out


def baselines_table(family):
    """The MODEL baselines of one family: success per tier, public, held-out, headline median."""
    key, head = HEADLINE[family]
    rows, pending = [], []
    for sid in _suite_ids(family):
        d = BENCH / sid / family
        if not (d / 'DONE').is_file():
            pending.append(sid)
            continue
        tiers = json.loads((d / 'tiers.json').read_text())['tiers']
        pub = {g['algorithm']: g for g in json.loads((d / 'public' / 'summary.json').read_text())['groups']}
        held = {g['algorithm']: g for g in json.loads((d / 'held_out' / 'summary.json').read_text())['groups']}
        rows.append('\\midrule')
        for i, algo in enumerate(sorted(tiers)):
            t = tiers[algo]
            cells = [f"{t[x]['successes']}/{t[x]['n']}" for x in ('easy', 'medium', 'hard')]
            m = pub[algo]['metrics'].get(key) or {}
            med = '--' if m.get('median') is None else f"{m['median']:.2f}"
            h = held.get(algo)
            rows.append(f"{tt(sid) if i == 0 else ''} & {tt(algo)} & {' & '.join(cells)} & "
                        f"{pub[algo]['successes']}/{pub[algo]['n']} & "
                        f"{'--' if h is None else str(h['successes']) + '/' + str(h['n'])} & {med} \\\\")
    note = (' Not yet run: ' + ', '.join(tt(s) for s in pending) + '.') if pending else ''
    return '\n'.join([
        f'% GENERATED by docs/paper/scripts/tables.py from docs/v2/r3/bench/*/{family}/',
        '\\begin{table}[t]', '\\centering', '\\scriptsize',
        f'\\caption{{\\evclass{{model}} baselines, {family}: successes per tier (easy/medium/hard), '
        f'on all public scenarios and on a held-out reference draw; {head.replace(chr(92) + " ", " ")} '
        f'is the public median.{note}}}',
        f'\\label{{tab:base-{family}}}', '\\setlength{\\tabcolsep}{2.5pt}',
        '\\begin{tabular}{llrrrrrr}', '\\toprule',
        f'suite & algorithm & easy & med. & hard & public & held-out & {head} \\\\',
        *rows, '\\bottomrule', '\\end{tabular}', '\\end{table}', ''])


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    out = {GEN / 'suites_table.tex': suites_table()}
    for fam in HEADLINE:
        out[GEN / f'baselines_{fam}.tex'] = baselines_table(fam)
    bad = 0
    for p, t in out.items():
        if a.check:
            if not p.is_file() or p.read_text() != t:
                print('DIFFERS', p.relative_to(REPO))
                bad += 1
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(t)
    print(f'{len(out)} table(s) {"checked" if a.check else "written"}')
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
