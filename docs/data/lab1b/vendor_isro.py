def fetch() -> bytes:
    """Return the upstream file's bytes at COMMIT, via ``gh api``."""
    return subprocess.run(
        ['gh', 'api', '-H', 'Accept: application/vnd.github.raw',
         f'repos/{REPO}/contents/{PATH}?ref={COMMIT}'],
        capture_output=True, check=True, timeout=60).stdout


def render(source: bytes) -> str:
    """Return the vendored module's text for ``source``."""
    text = source.decode('utf-8')
    lines = text.splitlines(keepends=True)
    blocks, table = [], []
    for first, last, what in SEGMENTS:
        seg = ''.join(lines[first - 1:last])
        digest = hashlib.sha256(seg.encode('utf-8')).hexdigest()
        table.append(f'    ({first}, {last}): {digest!r},\n')
        blocks.append(f'\n\n# >>> upstream l.{first}-{last}: {what}\n'
                      f'{seg}# <<< upstream l.{first}-{last}\n')
    head = HEADER.format(repo=REPO, commit=COMMIT, path=PATH,
                         file_sha=hashlib.sha256(source).hexdigest(),
                         segment_table=''.join(table))
    return head + ''.join(blocks)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[1])
    ap.add_argument('--source', help='a local copy of the upstream file')
    ap.add_argument('--check', action='store_true',
                    help='compare with the committed file; write nothing')
    args = ap.parse_args(argv)
    if args.source:
        with open(args.source, 'rb') as f:
            source = f.read()
    else:
        source = fetch()
    print(f'upstream {PATH} @ {COMMIT[:7]}: {len(source)} bytes, '
          f'sha256 {hashlib.sha256(source).hexdigest()}')
    text = render(source)
    if args.check:
        with open(OUT, encoding='utf-8') as f:
            same = f.read() == text
        print('vendored file matches upstream' if same else
              'vendored file DIFFERS from upstream')
        return 0 if same else 1
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'wrote {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
