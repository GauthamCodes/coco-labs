"""
Vendor the ISRO simulator's search functions into coco_lab, verbatim.

Reads ``astar_simulator_final_v3_6.py`` at a pinned commit of the private
repository ``GauthamCodes/isro-factory-pathfinding-simulator`` (through
``gh api``, which needs the owner's authentication, or from a local copy
with ``--source``), checks the whole file's SHA-256, cuts out the listed
line ranges, and writes ``coco_lab/coco_lab/isro/upstream_v3_6.py``: our
header and preamble, then each range byte for byte between marker
comments, with the SHA-256 of every range recorded in the file.
``coco_lab/test/test_isro.py`` re-hashes the ranges on every run, so an
edit to the vendored code fails the suite.

Usage (from the repository root)::

    python3 docs/data/lab1b/vendor_isro.py            # fetch with gh
    python3 docs/data/lab1b/vendor_isro.py --source astar_simulator_final_v3_6.py
    python3 docs/data/lab1b/vendor_isro.py --check    # verify, write nothing
"""

