"""
The ISRO simulator's search functions, VERBATIM. Do not edit.

GENERATED by ``docs/data/lab1b/vendor_isro.py`` from
``{repo}`` at commit ``{commit}``, file ``{path}``
(SHA-256 ``{file_sha}``), itself a transcription of the code listing in
the internship report. Every block between ``# >>> upstream`` and
``# <<< upstream`` markers is copied byte for byte from the upstream line
range it names; ``UPSTREAM_SEGMENTS`` records each block's SHA-256 and
``coco_lab/test/test_isro.py`` checks them on every run.

What is ours, above the first marker: this docstring, the imports the
functions use, and the module globals they read, which
:mod:`coco_lab.isro.historical` sets before each call. Pygame, drawing,
animation, file I/O and the event loop are not vendored; the search, cost,
heuristic, neighbour, reconstruction and smoothing code is.

The verbatim code keeps its original style, so this file is excluded from
the flake8 and pep257 linters (``test_flake8.py``, ``test_pep257.py``).
"""

