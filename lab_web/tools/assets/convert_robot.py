"""
COCO's robot, URDF -> glTF source (M4.1, M4.2; README §5.4).

  python3 lab_web/tools/assets/convert_robot.py OUT_DIR
  python3 lab_web/tools/assets/convert_robot.py --from-xacro    (needs ROS's xacro)

The robot description is `gazebo_models/urdf/coco_robo2.xacro` (frozen,
read-only). `--from-xacro` expands it with ROS's xacro and writes
`lab_web/tools/assets/coco_robo2.urdf`, whose first line records the xacro's
sha256; that committed URDF is what the conversion reads, so it runs where
ROS is not installed (CI). A test checks the recorded sha256 against the
xacro, so a changed xacro cannot go unnoticed.

Writes OUT_DIR/robot_src.glb, the pipeline's SOURCE at full resolution
(compress.mjs makes the served levels of detail, ADR 0006), with the joint
hierarchy kept:

  coco (root: ROS z-up -> glTF y-up)
    link:base_footprint
      joint:<name>          the joint's fixed origin (URDF <origin>)
        q:<name>            identity; the renderer rotates it about extras.axis
          link:<child>      the child link and its visuals

Standard library only.
"""

import hashlib
import math
import os
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from glb import GLB, rpy_to_quat  # noqa: E402
import mesh as M  # noqa: E402

REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
XACRO = os.path.join(REPO, 'gazebo_models', 'urdf', 'coco_robo2.xacro')
URDF = os.path.join(HERE, 'coco_robo2.urdf')
MESHES = os.path.join(REPO, 'gazebo_models', 'meshes')
Z_UP_TO_Y_UP = rpy_to_quat(-math.pi / 2, 0, 0)
HEADER = '<!-- generated by lab_web/tools/assets/convert_robot.py --from-xacro from gazebo_models/urdf/coco_robo2.xacro sha256 {} -->\n'


def xacro_sha256():
    return hashlib.sha256(open(XACRO, 'rb').read()).hexdigest()


def expand_xacro():
    """Expand the xacro with ROS's xacro. Its one `$(find gazebo_models)` (ros2_control's
    parameter file, irrelevant to visuals) is pointed at this repository, so no ament path
    is consulted -- an inherited AMENT_PREFIX_PATH can name unrelated workspaces (CLAUDE.md)."""
    sys.path.insert(0, '/opt/ros/jazzy/lib/python3.12/site-packages')
    import xacro  # noqa: E402
    text = open(XACRO).read().replace('$(find gazebo_models)', os.path.join(REPO, 'gazebo_models'))
    doc = xacro.parse(text)
    xacro.process_doc(doc)
    xml = doc.documentElement.toxml()
    return HEADER.format(xacro_sha256()) + xml.replace(os.path.join(REPO, 'gazebo_models'), '$(find gazebo_models)') + '\n'


def vec(s, n=3, default=0.0):
    return [float(x) for x in s.split()] if s else [default] * n


def origin(el):
    o = el.find('origin') if el is not None else None
    return (vec(o.get('xyz')), vec(o.get('rpy'))) if o is not None else ([0.0] * 3, [0.0] * 3)


def cylinder(radius, length, n=24):
    p = []
    for z in (-length / 2, length / 2):
        for i in range(n):
            a = 2 * math.pi * i / n
            p += [radius * math.cos(a), radius * math.sin(a), z]
    p += [0, 0, -length / 2, 0, 0, length / 2]
    t = []
    for i in range(n):
        j = (i + 1) % n
        t += [i, j, n + j, i, n + j, n + i, 2 * n, j, i, 2 * n + 1, n + i, n + j]
    return p, t


def geometry(g):
    """(positions, indices, description) for one URDF <geometry>."""
    if g.find('mesh') is not None:
        m = g.find('mesh')
        fn = m.get('filename').replace('package://gazebo_models/meshes', MESHES)
        p, t = M.read_stl(fn, tuple(vec(m.get('scale'), default=1.0)))
        return p, t, os.path.basename(fn)
    if g.find('box') is not None:
        p, _, t = M.box(vec(g.find('box').get('size')))
        return p, t, 'box'
    if g.find('cylinder') is not None:
        c = g.find('cylinder')
        p, t = cylinder(float(c.get('radius')), float(c.get('length')))
        return p, t, 'cylinder'
    raise ValueError('unknown geometry')


def build(root):
    colours = {m.get('name'): vec(m.find('color').get('rgba'), 4)
               for m in root.iter('material') if m.get('name') and m.find('color') is not None}
    links = {lk.get('name'): lk for lk in root.findall('link')}
    joints = root.findall('joint')
    children = {}
    for j in joints:
        children.setdefault(j.find('parent').get('link'), []).append(j)
    child_links = {j.find('child').get('link') for j in joints}
    base = [n for n in links if n not in child_links][0]
    g = GLB()
    vis_nodes = {}
    for name, lk in links.items():
        for k, vis in enumerate(lk.findall('visual')):
            p, t, src = geometry(vis.find('geometry'))
            mat = vis.find('material')
            matname = mat.get('name') if mat is not None else 'default'
            mi = g.material(matname, colours.get(matname, (0.6, 0.6, 0.6, 1)), 0.0, 0.7)
            mesh = g.mesh(f'{name}:{k}', p, t, mi, extras={'link': name, 'visual': k, 'source': src})
            xyz, rpy = origin(vis)
            vis_nodes.setdefault(name, []).append(
                g.node(f'visual:{name}:{k}', mesh=mesh, translation=xyz, rotation=rpy_to_quat(*rpy)))

    def link_node(name):
        kids = list(vis_nodes.get(name, []))
        for j in children.get(name, []):
            jn = j.get('name')
            xyz, rpy = origin(j)
            axis = vec(j.find('axis').get('xyz')) if j.find('axis') is not None else [1.0, 0.0, 0.0]
            lim = j.find('limit')
            extras = {'joint': jn, 'type': j.get('type'), 'axis': axis}
            if lim is not None and lim.get('lower') is not None:
                extras['limits'] = [float(lim.get('lower')), float(lim.get('upper'))]
            q = g.node(f'q:{jn}', children=[link_node(j.find('child').get('link'))], extras=extras)
            kids.append(g.node(f'joint:{jn}', translation=xyz, rotation=rpy_to_quat(*rpy), children=[q]))
        return g.node(f'link:{name}', children=kids)

    g.node('coco', rotation=Z_UP_TO_Y_UP, children=[link_node(base)], root=True,
           extras={'frame': 'base_footprint; ROS z-up, rotated to glTF y-up at this node'})
    return g


def main(argv):
    if argv[:1] == ['--from-xacro']:
        open(URDF, 'w').write(expand_xacro())
        print(f'{os.path.relpath(URDF, REPO)} from the xacro, sha256 {xacro_sha256()[:12]}')
        return
    out = argv[0]
    os.makedirs(out, exist_ok=True)
    text = open(URDF).read()
    root = ET.fromstring(text.split('\n', 1)[1])
    g = build(root)
    data = g.bytes(extras={'source': os.path.relpath(XACRO, REPO), 'xacro_sha256': text.split('sha256 ')[1].split()[0]})
    open(os.path.join(out, 'robot_src.glb'), 'wb').write(data)
    print(f'robot_src.glb: {len(data):,} B, {len(g.j["meshes"])} meshes')


if __name__ == '__main__':
    main(sys.argv[1:])
