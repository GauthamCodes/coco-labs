#!/usr/bin/env python3
"""
R1.3: write lab_web/src/workbench/meta.json from coco_lab.experiments (and --check it).

The Workbench builds its form from this file before any worker has booted: families,
algorithms and their labels, every parameter with its default and range, the metrics,
the statuses, the worlds this site ships (with their region zones) and the benchmark
suites. coco_lab stays the authority: a spec is validated by ``experiments.plan`` in
the worker; this file only draws the form. lab_web/tools/test_r1_meta.py keeps it current.

    python tools/r1/build_meta.py [--check]
"""
import json
import math
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / 'coco_lab'))
os.environ.setdefault('COCO_WORLDS', str(REPO / 'worlds'))

from coco_lab import experiments as ex  # noqa: E402

OUT = REPO / 'lab_web' / 'src' / 'workbench' / 'meta.json'
WORLD_TITLES = {'coco_arena_v1': 'Proving Ground (the COCO arena)',
                'coco_arena_v2': 'Proving Ground with terrain',
                'coco_depot_v1': 'COCO Depot',
                'coco_depot_colours_v1': 'COCO Depot with colour rods',
                'coco_depot_clutter_v1': 'COCO Depot, cluttered (COCO-Bench v1)'}


def _finite(v):
    return None if isinstance(v, float) and not math.isfinite(v) else v


def build():
    params = {fam: {k: {kk: _finite(vv) for kk, vv in p.items()} for k, p in table.items()}
              for fam, table in ex.PARAMS.items()}
    worlds = []
    for wid in ex.WORLDS:
        w = ex.world(wid)
        m = w.lab_map
        worlds.append({'id': wid, 'title': WORLD_TITLES[wid], 'spec_version': w.spec['spec_version'],
                       'resolution': m.resolution, 'origin': list(m.origin),
                       'width': m.width, 'height': m.height,
                       'regions': {k: list(v) for k, v in w.regions.items()},
                       'sha256': ex.world_sha256(wid)})
    suites = []
    for sid in ex.suites():
        s = ex.suite(sid)
        suites.append({'id': s['id'], 'version': s['version'], 'title': s['title'],
                       'world': s['world'], 'families': s['families'],
                       'n': len(s['scenarios']) if 'scenarios' in s else None,
                       'tests': s['tests']})
    return {'about': 'R1: generated by tools/r1/build_meta.py from coco_lab.experiments; '
                     'do not edit', 'schema': ex.SCHEMA, 'model': ex.MODEL,
            'families': list(ex.FAMILIES), 'algorithms': {k: list(v) for k, v in ex.ALGORITHMS.items()},
            'labels': ex.LABELS, 'params': params, 'metrics': ex.METRICS, 'statuses':
                {k: list(v) for k, v in ex.STATUSES.items()},
            'limits': ex.LIMITS, 'worlds': worlds, 'suites': suites,
            'fulltask': {'fetch_rush': {'world': ex.GAME_WORLDS['fetch_rush'],
                                        'seeds': list(ex.FETCH_RUSH_SEEDS),
                                        'modes': list(ex.FETCH_RUSH_MODES),
                                        'rules': ex.FETCH_RUSH_RULES},
                         'fetch_colour': {'world': ex.GAME_WORLDS['fetch_colour'],
                                          'colours': list(ex.FETCH_COLOURS),
                                          'rules': ex.FETCH_COLOUR_RULES}}}


def text():
    return json.dumps(build(), indent=1, sort_keys=True) + '\n'


if __name__ == '__main__':
    t = text()
    if '--check' in sys.argv:
        ok = OUT.exists() and OUT.read_text() == t
        print('meta.json is current' if ok else 'meta.json is STALE: run tools/r1/build_meta.py')
        sys.exit(0 if ok else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(t)
    print('wrote', OUT)
