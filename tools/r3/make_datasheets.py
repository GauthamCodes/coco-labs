import argparse
import hashlib
import json
from pathlib import Path
import statistics
import sys

REPO = Path(__file__).resolve().parents[2]
BENCH = REPO / 'coco_lab' / 'coco_lab' / 'benchmarks'
OUT = REPO / 'docs' / 'bench' / 'v1'

METRIC_DEFS = {
    'planning': [
        ('expansions', 'states taken off the open list (the algorithm\'s own count; None if it reports none)'),
        ('path_length_m', '$\\sum_i \\lVert c_{i+1} - c_i \\rVert \\cdot r$ over the path\'s cells $c_i$ (cell centres, resolution $r$)'),
        ('path_cost', '$\\sum$ edge costs, edge $=$ base $\\times (1 + w \\cdot \\text{cost}/252)$, $w = 2$ (8-connected paths only)'),
        ('min_clearance_m / mean_clearance_m', 'min / mean over the path\'s cells of (distance to the nearest obstacle $-$ robot radius 0.25 m)'),
        ('heading_change_rad', '$\\sum |\\mathrm{wrap}(\\theta_{i+1} - \\theta_i)|$ over consecutive path headings'),
        ('success', 'status `found` (a path from the start cell to the goal cell through no cell of cost $\\ge 253$)'),
        ('path_ratio (leaderboard)', 'path_length_m / Dijkstra\'s path length on the same costmap (grid-optimal; an any-angle path can be < 1)'),
    ],
    'control': [
        ('time_s', 'ticks $\\times$ dt (0.1 s) until the outcome'),
        ('path_length_m', 'distance driven by the TRUTH pose, $\\sum \\lVert p_{t+1} - p_t \\rVert$'),
        ('min_clearance_m / mean_clearance_m', 'over every tick, (clearance of the truth pose $-$ robot radius)'),
        ('contacts', 'number of contact onsets (the kinematic model\'s contact flag rising)'),
        ('final_goal_distance_m', 'truth to goal at the end'),
        ('success', 'status `succeeded`: FollowPath\'s goal checker (0.25 m, 0.25 rad) within `max_ticks`'),
    ],
    'localisation': [
        ('final_err_xy_m / final_err_yaw_rad', '$\\lVert \\hat p - p \\rVert$ and $|\\mathrm{wrap}(\\hat\\theta - \\theta)|$ at the end (belief vs truth)'),
        ('mean_err_xy_m / max_err_xy_m', 'over the error sampled every 1 s'),
        ('converged_s', 'first time from which 5 consecutive samples have error < 0.5 m and < 0.3 rad'),
        ('recovery_s', '(kidnap) the same, counted from the kidnap'),
        ('success', 'the robot reached the goal AND the final error is < 0.5 m and < 0.3 rad'),
    ],
    'fulltask': [
        ('deliveries / net_deliveries', 'objects delivered (net: minus penalties of the rules)'),
        ('time_to_complete_s', 'model seconds until the last delivery'),
        ('path_efficiency', 'reference route length / distance driven'),
        ('contacts', 'contact onsets'),
    ],
}

COMMON_LIMITS = [
    '**MODEL, kinematic.** Differential-drive planar kinematics with terrain following; no '
    'dynamics, contact forces, friction or tipping (AGENTS.md invariants). A success here is not a '
    'success on hardware; the R3 Gazebo + Nav2 subsets measure how far it carries to a full ROS 2 '
    'stack in simulation (STACK), still not hardware.',
    '**One robot, one robot model** (COCO: radius 0.22 m; inflation radius 0.25 m in the planning '
    'costmap). No multi-robot interaction.',
    '**No hardware.** No physical robot exists; nothing here is a REAL ROBOT RESULT.',
    '**Synthetic worlds.** The Proving Ground and the Depot are authored worlds (World Spec), not '
    'scans of real buildings.',
    '**Generator bias.** Scenarios are drawn from free cells with clearance > 0.35 m and must be '
    'connected on the planning grid; start or goal in tight spots and unreachable goals are '
    'therefore absent by construction. Filtered suites keep a scenario only if the reference A* '
    'path passes the filter, which biases them towards what A* finds.',
    '**Reference-path features.** Tiers depend on A*\'s path on the default costmap; another '
    'planner may find the same scenario easier or harder.',
]


def med(vals):
    vals = [v for v in vals if v is not None]
    return round(statistics.median(vals), 3) if vals else None


def datasheet(s, path):
    sid = s['id']
    scen = s['scenarios']
    feats = sorted({k for x in scen for k in (x.get('features') or {})})
    L = [f'# Datasheet · `{sid}` v{s["version"]}', '',
         f'*Generated by `tools/r3/make_datasheets.py` from `{path.relative_to(REPO)}` '
         f'(sha256 `{hashlib.sha256(path.read_bytes()).hexdigest()[:16]}…`); never edit by hand.*', '',
         '## Purpose', '', s['title'] + '.', '']
    if s.get('from_v0'):
        L += [f'Carried over from COCO-Bench v0 with **identical scenarios** (v0 scenarios sha256 '
              f'`{s["from_v0"]["scenarios_sha256"][:16]}…`); v1 adds features and tiers only.', '']
    L += ['## Composition', '',
          f'- Scenarios: **{len(scen)}**; families: {", ".join(s["families"])}'
          + (f'; algorithms: {", ".join(s["algorithms"])}' if s.get('algorithms') else ''),
          f'- World: ' + (f'`{s["world"]}` (spec sha256 `{s["world_sha256"][:16]}…`)'
                          if s.get('world') else ', '.join(f'`{w}`' for w in s['worlds'])),
          f'- Tiers: ' + ', '.join(f'{k} {v}' for k, v in s['tiers']['counts'].items()), '']
    conds = sorted({c for x in scen for c in x.get('config') or []})
    if conds or any('kidnap_at_s' in x for x in scen):
        L += ['## Conditions (scenario rules, applied at tick 0)', '']
        for c in conds:
            n = sum(1 for x in scen if c in (x.get('config') or []))
            L.append(f'- `{c}`: {n} scenarios')
        k = [x for x in scen if 'kidnap_at_s' in x]
        if k:
            L.append(f'- kidnap at {k[0]["kidnap_at_s"]} s to the scenario\'s `kidnap` point, '
                     'odometry untold (Lab 2\'s method; the goal is re-sent)')
        if any('actor_rule' in x for x in scen):
            L.append('- `actor_rule`: **yield** = the forklifts and walkers stop for COCO (Fetch '
                     'Rush rules 5, a scenario rule, not physics); **no_yield** = they keep their '
                     'schedule (rules 4). Each pair appears under both rules.')
        L.append('')
    L += ['## Generation', '', '```json', json.dumps(s['generator'], indent=1), '```', '',
          'Deterministic (hash version 3): `python tools/r3/make_suites_v1.py --check` regenerates '
          'every scenario byte for byte. Each scenario has its own `seed` for the run.', '',
          '## Features and tiers', '', f'Method: {s["tiers"]["method"]}. Tier features: '
          + ', '.join(f'`{f}`' for f in s['tiers']['features'])
          + f'. Cut scores: {s["tiers"]["cut_difficulty"]}.', '',
          '| feature | ' + ' | '.join(f'{t} (median)' for t in ('easy', 'medium', 'hard'))
          + ' | min | max |', '| --- |' + ' --- |' * 5]
    for f in feats:
        row = [med([x['features'].get(f) for x in scen if x.get('tier') == t])
               for t in ('easy', 'medium', 'hard')]
        allv = [x['features'].get(f) for x in scen if x['features'].get(f) is not None]
        L.append(f'| `{f}` | ' + ' | '.join(str(v) for v in row)
                 + f' | {min(allv)} | {max(allv)} |')
    L += ['', 'Feature definitions: `coco_lab/coco_lab/bench_v1.py` (module docstring).', '',
          '## Metrics', '']
    for fam in s['families']:
        L.append(f'**{fam}** (`{", ".join(s["metrics"][fam])}`):')
        L.append('')
        for k, d in METRIC_DEFS[fam]:
            L.append(f'- `{k}`: {d}')
        L.append('')
    L += ['`compute_ms` is wall time on the running device, reported but never compared across '
          'devices and never part of a hash.', '',
          '## Held-out scenarios', '', f'{s["held_out"]["n"]} per evaluation; '
          + s['held_out']['scheme'] + '.', '',
          '## Known biases and limitations', '']
    L += [f'- {x}' for x in COMMON_LIMITS]
    L += ['', '## Versioning', '',
          'Frozen: a change to any scenario, condition or the world is a new version '
          '(`<id>.v2.json`); results name the suite version, the model hash version (3), the '
          'experiment schema and the algorithm API they were made with. v0 files stay as they are.',
          '', '## Licence', '',
          'Apache-2.0, as the repository (`LICENSE`): the suite files, the worlds they name and '
          'this datasheet.', '']
    return '\n'.join(L)


def readme(suites):
    L = ['# COCO-Bench v1', '',
         '*Generated by `tools/r3/make_datasheets.py`; never edit by hand.*', '',
         'Frozen benchmark suites for mobile-robot navigation in COCO Lab\'s kinematic model '
         '(MODEL), with paired Gazebo + Nav2 subsets (STACK) in `docs/v2/r3/`. One datasheet each:',
         '', '| suite | family | scenarios | tiers (easy/medium/hard) | held-out per run | world |',
         '| --- | --- | --- | --- | --- | --- |']
    for s in suites:
        c = s['tiers']['counts']
        L.append(f'| [`{s["id"]}`]({s["id"]}.md) | {", ".join(s["families"])} | '
                 f'{len(s["scenarios"])} | {c["easy"]}/{c["medium"]}/{c["hard"]} | '
                 f'{s["held_out"]["n"]} | {s.get("world") or " + ".join(s["worlds"])} |')
    L += ['', 'Run a suite in the browser (Workbench → Benchmarks) or natively: '
          '`coco experiment run` with `"scenarios": {"kind": "suite", "id": ID, "version": 1}`.', '']
    return '\n'.join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    files = sorted(BENCH.glob('*.v1.json'))
    suites = [json.loads(p.read_text()) for p in files]
    out = {OUT / f'{s["id"]}.md': datasheet(s, p) for s, p in zip(suites, files)}
    out[OUT / 'README.md'] = readme(suites)
    bad = 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p, t in out.items():
        if a.check:
            if not p.is_file() or p.read_text() != t:
                print('DIFFERS', p)
                bad += 1
        else:
            p.write_text(t)
    print(f'{len(out)} files {"checked" if a.check else "written"}')
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
