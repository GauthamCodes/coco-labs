"""
Lab 1's teaching maps: 20 x 20, each built to show one thing.

Every fixture carries its purpose and the claim it exists to demonstrate,
and ``test/test_teaching.py`` checks each claim against the algorithms and
a networkx oracle -- a fixture whose claim stopped being true would fail,
not quietly teach something else.

A fixture is a map plus a start and a goal. The move model is NOT part of
the map (see :mod:`coco_lab.maps`); ``run`` holds the move model the
fixture is meant to be searched under, and a lesson may override it.
"""

from dataclasses import dataclass, field
from typing import Dict, Optional, Tuple

from .maps import LabMap

Cell = Tuple[int, int]


@dataclass(frozen=True)
class Fixture:
    """One teaching map: what it is for, and how to search it."""

    name: str
    purpose: str
    claim: str
    text: str
    run: Dict[str, object] = field(default_factory=dict)
    cost: Optional[Tuple[Tuple[Cell, Cell, float], ...]] = None

    def load(self) -> Tuple[LabMap, Cell, Cell]:
        """Return ``(map, start, goal)``; the map's id is ``teaching/<name>``."""
        m, marks = LabMap.from_ascii(self.text,
                                     map_id=f'teaching/{self.name}')
        if self.cost is not None:
            layer = [0.0] * (m.width * m.height)
            for (r0, c0), (r1, c1), value in self.cost:
                for r in range(r0, r1 + 1):
                    for c in range(c0, c1 + 1):
                        layer[r * m.width + c] = value
            m = LabMap(m.width, m.height, m.occupancy, layer, map_id=m.id)
        return m, marks['S'], marks['G']


