def load(name: str) -> Tuple[LabMap, Cell, Cell]:
    """Return ``(map, start, goal)`` for the fixture called ``name``."""
    try:
        return FIXTURES[name].load()
    except KeyError:
        raise KeyError(f'no teaching fixture {name!r}; '
                       f'have {sorted(FIXTURES)}') from None
