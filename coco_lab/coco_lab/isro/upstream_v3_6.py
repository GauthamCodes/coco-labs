def astar(start_pos, goal_pos):
    counter = count()
    open_set = []
    start = grid[start_pos[0]][start_pos[1]]
    goal = grid[goal_pos[0]][goal_pos[1]]
    for row in grid:
        for cell in row:
            cell.g = cell.f = float('inf')
            cell.parent = cell.direction = None
    start.g = 0
    start.f = heuristic(start, goal)
    heapq.heappush(open_set, (start.f, next(counter), start))
    blocked = get_blocked_positions()
    nodes = 0
    t0 = time.perf_counter()
    while open_set:
        f, _, curr = heapq.heappop(open_set)
        if f > curr.f:
            continue
        nodes += 1
        mark_cell_explored(curr, 'A*')
        if curr == goal:
            break
        for nbr in neighbors(curr):
            pos = (nbr.row, nbr.col)
            if pos in blocked or nbr.type == 'obstacle':
                continue
            new_g = curr.g + move_cost(curr, nbr)
            if curr.direction and direction(curr, nbr) != curr.direction:
                new_g += TURN_PENALTY
            if new_g < nbr.g:
                nbr.g = new_g
                nbr.f = new_g + heuristic(nbr, goal)
                nbr.parent = curr
                nbr.direction = direction(curr, nbr)
                heapq.heappush(open_set, (nbr.f, next(counter), nbr))
    path, curr = [], goal
    total_len, turns = 0, 0
    last_dir = None
    while curr and curr != start:
        path.append(curr)
        if curr.parent:
            total_len += move_cost(curr, curr.parent)
            dir_now = direction(curr.parent, curr)
            if last_dir and dir_now != last_dir:
                turns += 1
            last_dir = dir_now
        curr = curr.parent
    path.reverse()
    return path, {'length': round(total_len, 2), 'turns': turns, 'explored': nodes, 'time': round(time.perf_counter() - t0, 4)}


