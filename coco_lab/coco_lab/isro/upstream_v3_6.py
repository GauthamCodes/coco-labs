def heuristic(a, b):
    dx, dy = abs(a.row - b.row), abs(a.col - b.col)
    return dx + dy + (math.sqrt(2) - 2) * min(dx, dy)


def direction(a, b):
    return (b.row - a.row, b.col - a.col)


def move_cost(a, b):
    return math.sqrt(2) if abs(a.row - b.row) and abs(a.col - b.col) else 1


def neighbors(cell):
    for dx, dy in DIRS:
        r, c = cell.row + dx, cell.col + dy
        if 0 <= r < ROWS and 0 <= c < COLS:
            yield grid[r][c]
