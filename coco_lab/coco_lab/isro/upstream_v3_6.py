def bfs(start_pos, goal_pos):
    start = grid[start_pos[0]][start_pos[1]]
    goal = grid[goal_pos[0]][goal_pos[1]]
    for row in grid:
        for cell in row:
            cell.parent = None
    queue = deque([start])
    visited = {(start.row, start.col)}
    blocked = get_blocked_positions()
    t0 = time.perf_counter()
    while queue:
        curr = queue.popleft()
        mark_cell_explored(curr, 'BFS')
        if curr == goal:
            break
        for nbr in neighbors(curr):
            pos = (nbr.row, nbr.col)
            if pos in visited or pos in blocked or nbr.type == 'obstacle':
                continue
            visited.add(pos)
            nbr.parent = curr
            queue.append(nbr)
    path, curr = [], goal
    while curr and curr != start:
        path.append(curr)
        curr = curr.parent
    path.reverse()
    return path, {'length': len(path), 'turns': 0, 'explored': len(visited), 'time': round(time.perf_counter() - t0, 4)}
