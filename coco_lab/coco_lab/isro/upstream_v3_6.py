def line_of_sight(a, b):
    x0, y0 = a.col, a.row
    x1, y1 = b.col, b.row
    dx, dy = abs(x1 - x0), abs(y1 - y0)
    x, y = x0, y0
    n = 1 + dx + dy
    x_inc = 1 if x1 > x0 else -1
    y_inc = 1 if y1 > y0 else -1
    error = dx - dy
    dx *= 2
    dy *= 2
    for _ in range(n):
        if grid[y][x].type == 'obstacle' or (y, x) in static_obstacles:
            return False
        if error > 0:
            x += x_inc
            error -= dy
        else:
            y += y_inc
            error += dx
    return True


def smooth_path(path):
    if not path:
        return path
    new_path = [path[0]]
    i = 0
    while i < len(path) - 1:
        j = len(path) - 1
        while j > i:
            if line_of_sight(path[i], path[j]):
                break
            j -= 1
        new_path.append(path[j])
        i = j
    return new_path
