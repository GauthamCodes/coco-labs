"""
Write ``worlds/coco_arena_v2.yaml``: World Spec v2, v1 plus elevation (M4.2).

    python3 worlds/tools/make_coco_arena_v2.py [--check]

v2 is ``worlds/coco_arena_v1.yaml`` (itself generated from the stack's
sources) with ``spec_version``, ``id`` and ``title`` changed and one block
added, ``elevation`` (docs/v2/adr/0007-world-spec-elevation.md): the ramp
primitives of the four bays, derived from v1's own ``ramps`` block exactly as
``full_world_robo.launch.py traverse:=true`` spawns them -- an up-wedge with
its foot at ``foot_x``, a flat platform at the crest, a mirrored down-wedge
past it. So v1 and v2 cannot drift, and the v1 file, and every hash made from
it, is untouched. The World Spec <-> SDF agreement check
(lab_web/tools/test_worldspec_sdf.py) compares the result with the recorded
Gazebo world.

``--check`` exits 1 if the committed YAML or its canonical JSON differs.
"""

import argparse
import math
import os
import sys

HERE = os.path.dirname(os.path.realpath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
V1 = os.path.join(REPO, 'worlds', 'coco_arena_v1.yaml')
OUT = os.path.join(REPO, 'worlds', 'coco_arena_v2.yaml')
OUT_JSON = os.path.join(REPO, 'worlds', 'coco_arena_v2.json')


def num(v):
    """A number as the YAML writes it: integral floats as ints, else up to 12 significant digits."""
    r = round(float(v), 12)
    return str(int(r)) if r == int(r) else repr(r)


def elevation(ramps):
    rise = ramps['run'] * math.tan(math.radians(ramps['angle_deg']))
    crest = ramps['foot_x'] + ramps['run']
    far_foot = crest + ramps['platform_length'] + ramps['run']
    lines = ['elevation:']
    for i, y in enumerate(ramps['centres_y'], start=1):
        lines += [
            f'  - {{id: bay{i}_up, kind: wedge, foot: [{num(ramps["foot_x"])}, {num(y)}], yaw: 0, '
            f'run: {num(ramps["run"])}, rise: {num(rise)}, width: {num(ramps["width"])}}}',
            f'  - {{id: bay{i}_platform, kind: platform, center: [{num(crest + ramps["platform_length"] / 2)}, {num(y)}], '
            f'size: [{num(ramps["platform_length"])}, {num(ramps["width"])}, {num(rise)}]}}',
            f'  - {{id: bay{i}_down, kind: wedge, foot: [{num(far_foot)}, {num(y)}], yaw: {num(math.pi)}, '
            f'run: {num(ramps["run"])}, rise: {num(rise)}, width: {num(ramps["width"])}}}',
        ]
    return lines


def build():
    import yaml
    text = open(V1, encoding='utf-8').read()
    v1 = yaml.safe_load(text)
    body = text.split('\nspec_version: coco.world_spec.v1\n', 1)[1]
    body = body.replace('id: coco_arena_v1\n', 'id: coco_arena_v2\n', 1)
    body = body.replace(f'title: {v1["title"]}\n', f'title: {v1["title"]}, with elevation\n', 1)
    head = ['# COCO arena, World Spec v2 (docs/v2/WORLD_SPEC.md; docs/v2/adr/0007-world-spec-elevation.md).',
            '# GENERATED by worlds/tools/make_coco_arena_v2.py from worlds/coco_arena_v1.yaml (v1 plus',
            '# `elevation`, derived from its `ramps`); edit the sources and regenerate, never this file.',
            'spec_version: coco.world_spec.v2']
    return '\n'.join(head) + '\n' + body.rstrip('\n') + '\n' + '\n'.join(elevation(v1['ramps'])) + '\n'


def canonical(text):
    import yaml
    sys.path.insert(0, os.path.join(REPO, 'coco_lab'))
    from coco_lab.worldspec import canonical_bytes
    return canonical_bytes(yaml.safe_load(text))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[1])
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args(argv)
    text = build()
    data = canonical(text)
    if a.check:
        stale = open(OUT, encoding='utf-8').read() != text or open(OUT_JSON, 'rb').read() != data
        if stale:
            print('STALE: worlds/coco_arena_v2.yaml or .json; run worlds/tools/make_coco_arena_v2.py', file=sys.stderr)
            return 1
        print('worlds/coco_arena_v2.yaml and .json are current')
        return 0
    open(OUT, 'w', encoding='utf-8').write(text)
    open(OUT_JSON, 'wb').write(data)
    print(f'wrote {os.path.relpath(OUT, REPO)} and its canonical JSON')
    return 0


if __name__ == '__main__':
    sys.exit(main())
