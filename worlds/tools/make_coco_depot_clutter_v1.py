"""
Write worlds/coco_depot_clutter_v1.{yaml,json}: the Depot plus seeded kit pallets (R3.1).

COCO-Bench v1's depot-clutter-50 runs here. The clutter is part of the world itself -- kit
``pallet`` pieces like the Depot's own staging pallets (1.2 x 1.0 m, 1.4 m tall) -- so the
browser draws it, the LiDAR sees it and the same file compiles to Gazebo and Nav2
(tools/m6/gen_level.py): a scenario looks exactly as cluttered as it is.

Placement (seed 7100, 24 pallets): a pallet's centre is a free cell of the Depot with
clearance >= 1.5 m, >= 2.0 m from every actor lane and from the Depot's start, >= 2.5 m from
every pallet placed before it, >= 1.5 m from every kit object on the floor and >= 1.0 m from every
depot-nav-100 start and goal; each is axis aligned, its long side along x or y by a coin flip.
The placement is rejected and redrawn (seed + 1, ...) if any depot-nav-100 start/goal pair stops
being connected on the planning grid, or if the World Spec reader refuses it. Everything else is the Depot, unchanged.

    worlds/tools/make_coco_depot_clutter_v1.py [--check]
"""
import argparse
import copy
import os
import sys

import yaml

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(REPO, 'coco_lab'))
os.environ.setdefault('COCO_WORLDS', os.path.join(REPO, 'worlds'))

from coco_lab import experiments as ex  # noqa: E402
from coco_lab.bench_v1 import _seg_dist, actor_lanes  # noqa: E402
from coco_lab.exp_scenarios import World  # noqa: E402
from coco_lab.numerics import math  # noqa: E402
from coco_lab.rng import Rng  # noqa: E402
from coco_lab.worldspec import canonical_bytes, SpecError  # noqa: E402

ID = 'coco_depot_clutter_v1'
SEED, N = 7100, 24
SRC = os.path.join(REPO, 'worlds', 'coco_depot_v1.yaml')
OUT_YAML = os.path.join(REPO, 'worlds', f'{ID}.yaml')
OUT_JSON = os.path.join(REPO, 'worlds', f'{ID}.json')


def place(base, seed):
    w = ex.world('coco_depot_v1')
    lanes = actor_lanes(w)
    st = base['start']
    things = [k['at'] for k in base['kit'] if isinstance(k.get('at'), list) and len(k['at']) == 2]
    ends = [p[:2] for s in ex.suite('depot-nav-100', 0)['scenarios'] for p in (s['start'], s['goal'])]
    cands = w.candidates(1.5)
    rng = Rng(seed)
    got = []
    for _ in range(20000):
        if len(got) == N:
            break
        x, y = cands[rng.randrange(len(cands))]
        if min(_seg_dist((x, y), a, b) for a, b in lanes) < 2.0:
            continue
        if math.hypot(x - st['x'], y - st['y']) < 2.0:
            continue
        if any(math.hypot(x - t[0], y - t[1]) < 1.5 for t in things):
            continue
        if any(math.hypot(x - t[0], y - t[1]) < 1.0 for t in ends):
            continue
        if any(math.hypot(x - p[0], y - p[1]) < 2.5 for p in got):
            continue
        got.append((round(x, 2), round(y, 2), rng.randrange(2)))
    if len(got) < N:
        raise SystemExit(f'only {len(got)} pallets placed')
    return got


def build():
    with open(SRC, encoding='utf-8') as f:
        base = yaml.safe_load(f)
    pairs = ex.suite('depot-nav-100', 0)['scenarios']
    for seed in range(SEED, SEED + 50):
        spec = copy.deepcopy(base)
        spec['id'] = ID
        spec['title'] = 'COCO Depot, cluttered: the Depot plus 24 kit pallets (COCO-Bench v1)'
        spec['sources'] = dict(spec.get('sources') or {}, clutter=(
            f'worlds/tools/make_coco_depot_clutter_v1.py (seed {seed}, {N} kit pallets)'))
        for i, (x, y, turn) in enumerate(place(base, seed)):
            spec['kit'].append({'id': f'pallet_clutter_{i + 1:02d}', 'kind': 'pallet',
                                'center': [x, y], 'size': [1.0, 1.2] if turn else [1.2, 1.0],
                                'height': 1.4})
        try:
            w = World(spec)
        except SpecError:
            continue
        if all(w.component(*s['start'][:2]) == w.component(*s['goal'][:2]) >= 0
               for s in pairs):
            return spec, seed
    raise SystemExit('no placement keeps every depot-nav-100 pair connected')


def dump(spec, seed):
    head = ('# COCO Depot, cluttered (COCO-Bench v1, R3.1): coco_depot_v1 plus kit pallets.\n'
            f'# GENERATED by worlds/tools/make_coco_depot_clutter_v1.py (seed {seed}); never edit '
            'this file.\n')
    return head + yaml.safe_dump(spec, sort_keys=False, default_flow_style=None, width=100)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    spec, seed = build()
    text = dump(spec, seed)
    js = canonical_bytes(yaml.safe_load(text))
    if a.check:
        same = open(OUT_YAML, encoding='utf-8').read() == text and open(OUT_JSON, 'rb').read() == js
        print('up to date' if same else 'DIFFERS: regenerate')
        return 0 if same else 1
    with open(OUT_YAML, 'w', encoding='utf-8') as f:
        f.write(text)
    with open(OUT_JSON, 'wb') as f:
        f.write(js)
    print(OUT_YAML, OUT_JSON, 'seed', seed)
    return 0


if __name__ == '__main__':
    sys.exit(main())
